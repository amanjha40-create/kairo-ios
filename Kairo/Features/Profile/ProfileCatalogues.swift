    static func normalized(_ value: String) -> String {
        value.precomposedStringWithCompatibilityMapping
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .split(whereSeparator: \.isWhitespace)
            .joined(separator: " ")
            .lowercased()
    }

    static func resolve(
        _ value: String,
        in entries: [ProfileCatalogueEntry]
    ) -> ProfileCatalogueEntry? {
        let value = normalized(value)
        return entries.first { entry in
            ([entry.name] + entry.aliases).contains { normalized($0) == value }
        }
    }

    static func contains(
        _ entry: ProfileCatalogueEntry,
        values: [String],
        in entries: [ProfileCatalogueEntry]
    ) -> Bool {
        values.contains { resolve($0, in: entries)?.id == entry.id }
    }

    static func search(
        _ query: String,
        in entries: [ProfileCatalogueEntry]
    ) -> [ProfileCatalogueEntry] {
        let terms = normalized(query).split(separator: " ").map(String.init)
        guard !terms.isEmpty else { return entries }
        return entries.filter { entry in
            let labels = [entry.name] + entry.aliases + entry.searchTerms + [entry.category ?? ""]
            return labels.contains { label in
                let words = normalized(label).split { " /()-".contains($0) }.map(String.init)
                return terms.allSatisfy { term in words.contains { $0.hasPrefix(term) } }
            }
        }
    }
